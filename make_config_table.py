#!/usr/bin/env python3
"""Emit the per-model generation-settings table (config disclosure).

For each parameter: if generate_rollouts.py sets it we show our value; if the model's
Replicate API exposes it but we leave it unset we show the API default (in italics); if
the API does not expose the parameter at all we show N/A. This makes explicit which
settings are ours versus inherited provider defaults. The Cosmos3-Super row is added
from its own generation config. Prints a standalone LaTeX table to stdout.
"""
from generate_rollouts import MODELS
from constants import PRETTY

# Input-schema defaults read from the live Replicate model schemas
# (replicate.models.get(id).latest_version.openapi_schema) on 2026-07-10. A parameter
# absent from a model's entry below is NOT exposed by that model's API.
API_DEFAULTS = {
    "wan":        {"duration": 5, "resolution": "1080p", "enable_prompt_expansion": True, "negative_prompt": ""},
    "seedance":   {"duration": 5, "resolution": "720p",  "generate_audio": True},
    "happyhorse": {"duration": 5, "resolution": "1080p"},
    "veo31":      {"duration": 8, "resolution": "1080p", "negative_prompt": None, "generate_audio": True},
    "runway45":   {"duration": 5},
}


def cell(model_key, cfg, param, fmt):
    """Italic if the effective value equals the provider's API default (whether we set it
    to that value or left it unset); plain if we deliberately set a non-default value;
    N/A if the API does not expose the parameter."""
    default = API_DEFAULTS.get(model_key, {})
    exposed = param in default
    if param not in cfg and not exposed:
        return "N/A"
    if param in cfg:
        val = cfg[param]
        is_default = exposed and val == default[param]
    else:                      # exposed but unset -> the API default applies
        val = default[param]
        is_default = True
    s = fmt(val) if val is not None else "unset"
    return (r"\textit{" + s + "}") if is_default else s


def dur(v): return f"{v} s"
def res(v): return str(v)
def pe(v):  return "yes" if v else "no"
def neg(v): return r'\texttt{""}' if v == "" else ("set" if v else "unset")
def aud(v): return "off" if v is False else "on"


def row_fields(k):
    cfg = MODELS[k]["input"]("<frame_url>", 0, "<prompt>")
    return {
        "id": MODELS[k]["id"],
        "duration": cell(k, cfg, "duration", dur),
        "resolution": cell(k, cfg, "resolution", res),
        "prompt_expansion": cell(k, cfg, "enable_prompt_expansion", pe),
        "negative_prompt": cell(k, cfg, "negative_prompt", neg),
        "audio": cell(k, cfg, "generate_audio", aud),
    }


# Cosmos3-Super is generated locally (cosmos/cosmos3_super_batch.py); authoritative
# benchmark config = 121 frames @ 24 fps (~5.04 s), 1280x704, steps 35, guidance 6.0.
# It exposes no prompt-expansion or audio toggle; a negative prompt is set.
COSMOS_ROW = {
    "id": "nvidia/Cosmos3-Super (local)",
    "duration": r"5.04 s$^\dagger$",
    "resolution": r"1280$\times$704",
    "prompt_expansion": "N/A",
    "negative_prompt": r"\textit{set}",   # the Cosmos3-docs default negative prompt
    "audio": "N/A",
}

ORDER = ["wan", "seedance", "happyhorse", "veo31", "runway45"]


def main():
    print(r"% Per-model video-generation settings. Auto-generated by make_config_table.py.")
    print(r"\begin{table}[t]")
    print(r"\centering")
    print(r"\caption{Per-model video-generation settings. All models receive the same conditioning")
    print(r"frames, text prompts, and 32 fixed seeds; only the settings below differ. \emph{Italic}")
    print(r"marks a value equal to the provider's API default (whether we set it explicitly or left")
    print(r"it unset); N/A means the")
    print(r"model's API does not expose that parameter. Per-model durations are the shortest length")
    print(r"each provider offers; WAN-2.7 (3\,s) and SeeDance-2.0 (4\,s) accept an arbitrary integer")
    print(r"duration and were fixed slightly above the API minimum.}")
    print(r"\label{tab:gen_settings}")
    print(r"\small")
    print(r"\begin{tabular}{l l c c c c c}")
    print(r"\toprule")
    print(r"Model & Replicate / source ID & Duration & Resolution & Prompt exp. & Neg.\ prompt & Audio \\")
    print(r"\midrule")
    for k in ORDER:
        f = row_fields(k)
        print(f"{PRETTY[k]} & \\texttt{{{f['id']}}} & {f['duration']} & {f['resolution']} & "
              f"{f['prompt_expansion']} & {f['negative_prompt']} & {f['audio']} \\\\")
    c = COSMOS_ROW
    print(f"Cosmos3-Super & {c['id']} & {c['duration']} & {c['resolution']} & "
          f"{c['prompt_expansion']} & {c['negative_prompt']} & {c['audio']} \\\\")
    print(r"\bottomrule")
    print(r"\end{tabular}")
    print(r"\\[2pt]{\footnotesize $^\dagger$Cosmos3-Super: 121 frames @ 24\,fps; "
          r"\texttt{steps}=35, \texttt{guidance\_scale}=6.0 (\texttt{cosmos/cosmos3\_super\_batch.py}).}")
    print(r"\end{table}")


if __name__ == "__main__":
    main()
